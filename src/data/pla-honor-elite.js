const titles = new Map(PLA_HONORS.map(h => [h.name, h]));
export function honorForUnit(unit) {
  if (!unit || typeof unit !== 'object') return null;
  const explicit = [unit.honorName,unit.honorTitle,unit.honoraryName,unit.honorDesignation,unit.name,unit.displayName].filter(v=>typeof v==='string').map(v=>v.trim());
  // Only exact honors or explicitly annotated unit names; no fuzzy matches.
  for (const title of explicit) {
    if (titles.has(title)) return titles.get(title);
    const matched = [...titles.keys()].find(name => title.endsWith('（'+name+'）') || title.endsWith('('+name+')'));
    if (matched) return titles.get(matched);
  }
  return null;
}
export function eliteMultiplier(unit) {
  if (!unit || unit.elite === false || unit.honorParticipationDisabled === true) return 1;
  if (unit.honorId) {
    const honor = PLA_HONORS.find(h=>h.id===unit.honorId);
    if (honor) return 2;
  }
  return honorForUnit(unit) ? 2 : 1;
}
